#!/usr/bin/env python3
"""Generates trainers.h (the boss ladder) and badges.h (its badges).

  python3 tools/gen_ladders.py

A STAND-IN until phase 2 of the cutover brings Time Stranger's 13-boss ladder with
Hard mode. It keeps TS_BOSS_TBL's slots and levels, and a boss with no public art
gives way to a form with art of the same stage, so every fight can be drawn. The
badges are DRAWN here, from geometry -- eight shapes, coloured by the area boss's
element -- so nothing in them is anybody else's artwork.
"""
import math
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import ts_roster as R

ROOT = os.path.join(os.path.dirname(__file__), '..')
PX = 32
AREAS = ['NATIVE FOREST', 'GEAR SAVANNA', 'DRILL TUNNEL', 'TROPIC JUNGLE', 'OVERDELL', 'FREEZELAND',
         'MT. PANORAMA', 'GREYLORD HALL', 'ELITE', 'ELITE', 'ELITE', 'ELITE', 'CHAMPION']
# Read from types.h so a badge is the colour of its element's chip.
ELEMENT_ACCENT = re.findall(r'0x[0-9A-F]{4}', re.search(
    r'ELEMENT_COL\[[^\]]*\] = \{(.*?)\}', open(os.path.join(ROOT, 'types.h')).read(), re.S).group(1))


def ladder():
    """[(dex, level)] for the 13 slots of TS_BOSS_TBL, each drawable and each different."""
    text = open(os.path.join(ROOT, 'ts_dex.h')).read()
    slots = re.findall(r'^\s*\{ (\d+), (\d+), TS_ST_(\w+), TS_BOSS_\w+ \},', text, re.M)
    art = R.art_map()
    used = set()
    out = []
    for dex, level, stage in slots:
        dex, stage = int(dex), R.STAGES.index(stage)
        if dex not in art:
            # The strongest stage that has art, no higher than the boss's own. Ladders
            # end at Mega on public art: no Mega+ form has a sprite.
            while not [d for d in art if R.ROSTER[d]['stage'] == stage and d not in used]:
                stage -= 1
            pool = [d for d in sorted(art) if R.ROSTER[d]['stage'] == stage and d not in used]
            dex = pool[len(out) % len(pool)]
        used.add(dex)
        out.append((dex, int(level)))
    return out


def trainers():
    o = ['#pragma once\n#include <stdint.h>\n\n',
         '// GENERATED by tools/gen_ladders.py from ts_dex.h and the art map - do not edit\n',
         '//\n// The boss ladder: eight areas, four elite and a champion, one Digimon each.\n'
         '// A stand-in with TS_BOSS_TBL\'s slots and levels and forms that have art; phase 2\n'
         '// of the cutover brings the real 13-boss ladder and Hard mode.\n\n',
         'struct Trainer {\n  const char *name;\n  const char *place;   // the area, or ELITE / CHAMPION\n'
         '  uint16_t dex;\n  uint8_t level;\n};\n\n',
         '#define TRAINER_COUNT 13\n#define TRAINER_GYMS 8\n#define TRAINER_ELITE4 4\n\n',
         'static const Trainer TRAINERS[TRAINER_COUNT] = {\n']
    for (dex, level), place in zip(ladder(), AREAS):
        o.append('  { %-18s %-16s %3d, %2d },\n' % ('"%s",' % R.ROSTER[dex]['name'], '"%s",' % place, dex, level))
    o.append('};\n\n')
    o.append('// Hard mode reruns the same ladder with a smarter AI.\n#define HARD_IV 31\n#define EASY_IV 16\n')
    open(os.path.join(ROOT, 'trainers.h'), 'w').write(''.join(o))


def rgb565(c):
    r, g, b = c
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)


def rgb_of(c565):
    v = int(c565, 16)
    return ((v >> 11) & 31) << 3, ((v >> 5) & 63) << 2, (v & 31) << 3


def shade(c, f):
    return tuple(max(0, min(255, int(v * f))) for v in c)


def inside(shape, x, y):
    """Is (x, y), centred at 0 with radius ~1, inside badge shape n?"""
    r = math.hypot(x, y)
    a = math.atan2(y, x)
    if shape == 0:   # disc
        return r <= 1
    if shape == 1:   # diamond
        return abs(x) + abs(y) <= 1.05
    if shape == 2:   # hexagon
        return max(abs(x) * 0.866 + abs(y) * 0.5, abs(y)) <= 0.92
    if shape == 3:   # shield
        if -0.9 <= y <= 0.35:
            return abs(x) <= 0.85
        return y > 0.35 and abs(x) <= 0.85 * (1 - (y - 0.35) / 0.7)
    if shape == 4:   # five-point star
        k = (math.cos(5 * (a + math.pi / 2)) + 1) / 2
        return r <= 0.5 + 0.5 * k
    if shape == 5:   # ring
        return 0.45 <= r <= 1
    if shape == 6:   # triangle
        return y <= 0.75 and abs(x) <= (y + 0.95) * 0.62
    if shape == 7:   # cross
        return (abs(x) <= 0.34 and abs(y) <= 1) or (abs(y) <= 0.34 and abs(x) <= 1)
    return False


def badge(shape, base):
    """32x32 indices into a 5-colour palette: 0 outline, 1 body, 2 shade,
    3 light, 4 the version's gem in the middle; 255 transparent."""
    light = tuple(min(255, v + 90) for v in base)
    pal = [(0x1b, 0x1b, 0x25), base, shade(base, 0.68), light, (0xf4, 0xf8, 0xea)]
    grid = [[255] * PX for _ in range(PX)]
    c = (PX - 1) / 2
    for y in range(PX):
        for x in range(PX):
            u, v = (x - c) / 13.5, (y - c) / 13.5
            if inside(shape, u, v):
                grid[y][x] = 2 if (u + v) > 0.55 else (3 if (u + v) < -0.9 else 1)
    # gem
    for y in range(PX):
        for x in range(PX):
            if grid[y][x] != 255 and math.hypot(x - c, y - c) <= 3.2:
                grid[y][x] = 4
    # outline
    out = [row[:] for row in grid]
    for y in range(PX):
        for x in range(PX):
            if grid[y][x] == 255:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                xx, yy = x + dx, y + dy
                if not (0 <= xx < PX and 0 <= yy < PX) or grid[yy][xx] == 255:
                    out[y][x] = 0
                    break
    return pal, out


def badges():
    o = ['// GENERATED by tools/gen_ladders.py - do not edit\n//\n'
         '// One badge per area boss: eight shapes, coloured by the boss\'s element.\n'
         '// Drawn from geometry, so they are this project\'s own artwork.\n'
         '#pragma once\n#include <stdint.h>\n\n',
         '#define BADGE_PX %d\n\n' % PX]
    row = []
    for i, (dex, _level) in enumerate(ladder()[:8]):
        pal, grid = badge(i, rgb_of(ELEMENT_ACCENT[R.home_element(dex)]))
        tag = 'BADGE_%d' % i
        o.append('// %s\n' % R.ROSTER[dex]['name'])
        o.append('static const uint16_t %s_PAL[%d] = { %s };\n'
                 % (tag, len(pal), ', '.join('0x%04X' % rgb565(p) for p in pal)))
        o.append('static const uint8_t %s_IDX[%d] = {\n' % (tag, PX * PX))
        for r in grid:
            o.append('  ' + ','.join(str(v) for v in r) + ',\n')
        o.append('};\n')
        row.append('{ %s_PAL, %s_IDX }' % (tag, tag))
    o.append('\nstruct BadgeArt { const uint16_t *pal; const uint8_t *idx; };\n')
    o.append('static const BadgeArt BADGES_ART[8] = {\n  %s,\n};\n' % ',\n  '.join(row))
    open(os.path.join(ROOT, 'badges.h'), 'w').write(''.join(o))


if __name__ == '__main__':
    trainers()
    badges()
    print('trainers.h + badges.h: one ladder of %d' % len(ladder()))
