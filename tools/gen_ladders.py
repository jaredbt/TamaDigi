#!/usr/bin/env python3
"""Generates trainers.h (what the boss ladder adds to the data) and badges.h (its badges).

  python3 tools/gen_ladders.py

The ladder itself is TS_BOSS_TBL in ts_dex.h: 13 single Digimon at their levels and
stages, from the design table. This adds what the data does not hold: each slot's
area name, and a STAND-IN for each boss that has no public art -- a form with art of
the boss's stage (or the strongest stage below it that has any; no Mega+ form has
public art, so Apocalymon's is a Mega). The firmware fights the real boss whenever
it can be drawn (`bossForm()` in pet.cpp asks `speciesShowable()`), so a private
build with the boss's own art switches to it with no change here.

The badges are DRAWN here, from geometry -- eight shapes, coloured by the real area
boss's element -- so nothing in them is anybody else's artwork.
"""
import math
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import ts_roster as R

ROOT = os.path.join(os.path.dirname(__file__), '..')
PX = 32
AREAS = ['NATIVE FOREST', 'GEAR SAVANNA', 'DRILL TUNNEL', 'TROPIC JUNGLE', 'OVERDELL', 'FREEZELAND',
         'MT. PANORAMA', 'GREYLORD HALL', 'ELITE', 'ELITE', 'ELITE', 'ELITE', 'CHAMPION']
# Read from types.h so a badge is the colour of its element's chip.
ELEMENT_ACCENT = re.findall(r'0x[0-9A-F]{4}', re.search(
    r'ELEMENT_COL\[[^\]]*\] = \{(.*?)\}', open(os.path.join(ROOT, 'types.h')).read(), re.S).group(1))


def bosses():
    """[(dex, level, stage)] of TS_BOSS_TBL, in unlock order."""
    text = open(os.path.join(ROOT, 'ts_dex.h')).read()
    slots = re.findall(r'^\s*\{ (\d+), (\d+), TS_ST_(\w+), TS_BOSS_\w+ \},', text, re.M)
    if len(slots) != len(AREAS):
        raise SystemExit('gen_ladders: TS_BOSS_TBL has %d slots, AREAS %d' % (len(slots), len(AREAS)))
    return [(int(d), int(l), R.STAGES.index(st)) for d, l, st in slots]


def stand_ins():
    """[dex or 0] per slot: 0 when the boss has public art, else a form with art.

    Same stage as the boss, stepping down while a stage has none; never a form another
    slot already uses; the boss's own attribute first (the ladder is villains, mostly
    Virus), then the form whose level-99 stats are nearest the boss's."""
    art = R.art_map()
    ladder = bosses()
    used = {d for d, _l, _s in ladder if d in art}
    out = []
    for dex, _level, stage in ladder:
        if dex in art:
            out.append(0)
            continue
        boss = R.ROSTER[dex]
        st = stage
        while st > 0 and not [d for d in art if R.ROSTER[d]['stage'] == st and d not in used]:
            st -= 1
        pool = [d for d in sorted(art) if R.ROSTER[d]['stage'] == st and d not in used]
        if not pool:
            raise SystemExit('gen_ladders: no stand-in left for %s' % boss['name'])
        pick = min(pool, key=lambda d: (R.ROSTER[d]['attr'] != boss['attr'],
                                        abs(sum(R.ROSTER[d]['max']) - sum(boss['max'])), d))
        used.add(pick)
        out.append(pick)
    return out


def trainers():
    o = ['#pragma once\n#include <stdint.h>\n#include "ts_dex.h"\n\n',
         '// GENERATED by tools/gen_ladders.py from ts_dex.h and the art map - do not edit\n',
         '//\n// The boss ladder is TS_BOSS_TBL: eight areas (a badge each), four elites and a\n'
         '// champion, one Digimon each, unlocked in order. This adds each slot\'s area and\n'
         '// a stand-in for a boss with no public art. bossForm() in pet.cpp is the one\n'
         '// answer to which Digimon is fought: the boss itself when it can be drawn.\n\n',
         '#define TRAINER_COUNT TS_BOSS_COUNT\n#define TRAINER_GYMS 8\n#define TRAINER_ELITE4 4\n'
         '#define TRAINER_CHAMPION (TRAINER_COUNT - 1)\n\n',
         'static const char *const TRAINER_PLACE[TRAINER_COUNT] = {\n']
    for place in AREAS:
        o.append('  "%s",\n' % place)
    o.append('};\n\n')
    o.append('// A form with public art fought in the boss\'s place, 0 when the boss has art.\n'
             'static const uint16_t TRAINER_STAND_IN[TRAINER_COUNT] = {\n')
    for (dex, level, stage), sub in zip(bosses(), stand_ins()):
        note = R.ROSTER[dex]['name'] + (' -> %s (%s)' % (R.ROSTER[sub]['name'], R.STAGES[R.ROSTER[sub]['stage']])
                                        if sub else ' (has art)')
        o.append('  %3d,  // %s\n' % (sub, note))
    o.append('};\n')
    open(os.path.join(ROOT, 'trainers.h'), 'w').write(''.join(o))


def rgb565(c):
    r, g, b = c
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)


def rgb_of(c565):
    v = int(c565, 16)
    return ((v >> 11) & 31) << 3, ((v >> 5) & 63) << 2, (v & 31) << 3


def shade(c, f):
    return tuple(max(0, min(255, int(v * f))) for v in c)


def inside(shape, x, y):
    """Is (x, y), centred at 0 with radius ~1, inside badge shape n?"""
    r = math.hypot(x, y)
    a = math.atan2(y, x)
    if shape == 0:   # disc
        return r <= 1
    if shape == 1:   # diamond
        return abs(x) + abs(y) <= 1.05
    if shape == 2:   # hexagon
        return max(abs(x) * 0.866 + abs(y) * 0.5, abs(y)) <= 0.92
    if shape == 3:   # shield
        if -0.9 <= y <= 0.35:
            return abs(x) <= 0.85
        return y > 0.35 and abs(x) <= 0.85 * (1 - (y - 0.35) / 0.7)
    if shape == 4:   # five-point star
        k = (math.cos(5 * (a + math.pi / 2)) + 1) / 2
        return r <= 0.5 + 0.5 * k
    if shape == 5:   # ring
        return 0.45 <= r <= 1
    if shape == 6:   # triangle
        return y <= 0.75 and abs(x) <= (y + 0.95) * 0.62
    if shape == 7:   # cross
        return (abs(x) <= 0.34 and abs(y) <= 1) or (abs(y) <= 0.34 and abs(x) <= 1)
    return False


def badge(shape, base):
    """32x32 indices into a 5-colour palette: 0 outline, 1 body, 2 shade,
    3 light, 4 the version's gem in the middle; 255 transparent."""
    light = tuple(min(255, v + 90) for v in base)
    pal = [(0x1b, 0x1b, 0x25), base, shade(base, 0.68), light, (0xf4, 0xf8, 0xea)]
    grid = [[255] * PX for _ in range(PX)]
    c = (PX - 1) / 2
    for y in range(PX):
        for x in range(PX):
            u, v = (x - c) / 13.5, (y - c) / 13.5
            if inside(shape, u, v):
                grid[y][x] = 2 if (u + v) > 0.55 else (3 if (u + v) < -0.9 else 1)
    # gem
    for y in range(PX):
        for x in range(PX):
            if grid[y][x] != 255 and math.hypot(x - c, y - c) <= 3.2:
                grid[y][x] = 4
    # outline
    out = [row[:] for row in grid]
    for y in range(PX):
        for x in range(PX):
            if grid[y][x] == 255:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                xx, yy = x + dx, y + dy
                if not (0 <= xx < PX and 0 <= yy < PX) or grid[yy][xx] == 255:
                    out[y][x] = 0
                    break
    return pal, out


def badges():
    o = ['// GENERATED by tools/gen_ladders.py - do not edit\n//\n'
         '// One badge per area boss: eight shapes, coloured by the boss\'s element.\n'
         '// Drawn from geometry, so they are this project\'s own artwork.\n'
         '#pragma once\n#include <stdint.h>\n\n',
         '#define BADGE_PX %d\n\n' % PX]
    row = []
    for i, (dex, _level, _stage) in enumerate(bosses()[:8]):
        pal, grid = badge(i, rgb_of(ELEMENT_ACCENT[R.home_element(dex)]))
        tag = 'BADGE_%d' % i
        o.append('// %s\n' % R.ROSTER[dex]['name'])
        o.append('static const uint16_t %s_PAL[%d] = { %s };\n'
                 % (tag, len(pal), ', '.join('0x%04X' % rgb565(p) for p in pal)))
        o.append('static const uint8_t %s_IDX[%d] = {\n' % (tag, PX * PX))
        for r in grid:
            o.append('  ' + ','.join(str(v) for v in r) + ',\n')
        o.append('};\n')
        row.append('{ %s_PAL, %s_IDX }' % (tag, tag))
    o.append('\nstruct BadgeArt { const uint16_t *pal; const uint8_t *idx; };\n')
    o.append('static const BadgeArt BADGES_ART[8] = {\n  %s,\n};\n' % ',\n  '.join(row))
    open(os.path.join(ROOT, 'badges.h'), 'w').write(''.join(o))


if __name__ == '__main__':
    trainers()
    badges()
    print('trainers.h + badges.h: one ladder of %d, %d stand-ins' % (len(bosses()), sum(1 for d in stand_ins() if d)))
